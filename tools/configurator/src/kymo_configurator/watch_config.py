"""Live variables (KymoWatch): settings, linker-symbol presets and the generated init file.

The project keeps one top-level ``watch`` object. It is optional: an absent object means
the defaults below, so projects written before this existed stay valid and unchanged.
"""
from __future__ import annotations

from typing import Any

# Linker symbols that enclose .data and .bss (contiguous in RAM on these targets).
WATCH_SYMBOLS: dict[str, tuple[str, str] | None] = {
    "esp32": ("_data_start", "_bss_end"),
    "stm32": ("_sdata", "_ebss"),
    "cmsis": ("__data_start__", "__bss_end__"),
    "custom": None,
}
WATCH_DEFAULTS: dict[str, Any] = {
    "symbols": "esp32", "range_start": "_data_start", "range_end": "_bss_end",
    "range2_start": "", "range2_end": "", "build_id": "", "slots": 8, "min_period_ms": 5,
}
WATCH_KEYS = frozenset(WATCH_DEFAULTS)


def watch_settings(project: dict[str, Any]) -> dict[str, Any]:
    """Effective watch settings: stored values over defaults."""
    stored = project.get("watch", {})
    settings = dict(WATCH_DEFAULTS)
    if isinstance(stored, dict):
        settings.update({key: value for key, value in stored.items() if key in WATCH_KEYS})
    return settings


def watch_ranges(settings: dict[str, Any]) -> list[tuple[str, str]]:
    """Configured (start, end) symbol pairs; a pair with an empty side is ignored."""
    pairs = [(settings.get("range_start", ""), settings.get("range_end", "")),
             (settings.get("range2_start", ""), settings.get("range2_end", ""))]
    return [(start, end) for start, end in pairs if start and end]


def watch_macros(settings: dict[str, Any]) -> dict[str, str]:
    """Header macros for the slot count and the shortest sampling period."""
    return {"KYMO_MAX_WATCHES": f"{int(settings['slots'])}u",
            "KYMO_WATCH_MIN_PERIOD_MS": f"{int(settings['min_period_ms'])}u"}


WATCH_HEADER = """#if KYMO_EFFECTIVE_WATCH
extern KymoWatch kymo_generated_watch;
KymoStatus kymo_generated_watch_init(void);
#endif
"""

_SEPARATOR = "/" + "*" * 79


def render_watch_source(settings: dict[str, Any]) -> str:
    """kymo_generated_watch.cpp: allowed ranges from linker symbols plus the build ID."""
    ranges = watch_ranges(settings)
    build_id = settings.get("build_id", "")
    symbols = sorted({name for pair in ranges for name in pair})
    lines = ["/* Generated by Kymo Configurator. Do not edit; edit kymo.project.json. */",
             "#include <kymo_generated_config.h>",
             "#if KYMO_EFFECTIVE_WATCH",
             "/* Linker symbols that enclose the readable memory. */"]
    lines += [f'extern "C" uint8_t {name};' for name in symbols]
    if build_id:
        lines += ["/* User-owned: points *id at the build ID and returns its length (0 = unknown). */",
                  f'extern "C" size_t {build_id}(const uint8_t **id);']
    lines += ["", "KymoWatch kymo_generated_watch;", "",
              _SEPARATOR, " * kymo_generated_watch_init", " " + "*" * 78 + "/",
              "KymoStatus kymo_generated_watch_init(void)", "{",
              f"    static KymoWatchRange ranges[{max(1, len(ranges))}u];",
              "    const uint8_t *id = nullptr;", "    size_t id_length = 0u;"]
    for index, (start, end) in enumerate(ranges):
        lines += [f"    ranges[{index}].start = (uint32_t)(uintptr_t)&{start};",
                  f"    ranges[{index}].length = (uint32_t)((uintptr_t)&{end} - (uintptr_t)&{start});"]
    if build_id:
        lines.append(f"    id_length = {build_id}(&id);")
    lines += [f"    const KymoWatchConfig config = {{ ranges, {len(ranges)}u, id, id_length, nullptr, nullptr }};",
              "    return KymoWatch_Init(&kymo_generated_watch, &config);", "}",
              "#endif /* KYMO_EFFECTIVE_WATCH */", ""]
    return "\n".join(lines)


def apply_symbol_preset(doc: dict[str, Any], preset: str) -> None:
    """Copy a preset's symbols into the first range; 'custom' keeps the entered names."""
    pair = WATCH_SYMBOLS.get(preset)
    if pair is not None:
        watch = doc.setdefault("watch", {})
        watch["range_start"], watch["range_end"] = pair
